import assert from 'node:assert/strict';
import { salaryPeriodApplications, saveSalaryConfig, generateSalaryPeriods, saveSalaryPeriod, postSalaryPayment, salaryPeriodTotals, salaryPaymentValid, unlinkSalaryPayment } from '../lib/salary-tracking.ts';
import { totals } from '../lib/finance-ledger.ts';
import { resetFinanceData } from '../lib/finance-reset.ts';
const today='2026-10-14';
const initial={accounts:[{id:'a',name:'Banco ficticio',type:'Banco',active:true,balance:0}],envelopes:[{id:'e',name:'Hogar',balance:0}],loans:[],movements:[]};
const config={id:'c',employer:'Ejemplo local',name:'Semanal',currency:'CRC',base:1000,frequency:'Semanal',start:'2026-09-01',payOffset:1,workDays:[1,2,3,4,5],active:true};
let d=saveSalaryConfig(initial,config,null);
d=generateSalaryPeriods(d,'c',3);
assert.equal(d.salary.periods.length,3);
assert.equal(salaryPeriodTotals(d,d.salary.periods[0]).projected,1000);
assert.equal(salaryPeriodTotals(d,d.salary.periods[0]).pending,0);
assert.deepEqual(totals(d),{accounts:0,assigned:0,unassigned:0});
const [p1,p2]=d.salary.periods;
d=saveSalaryPeriod(d,{...p1,earned:true,concepts:[...p1.concepts,{id:'moto',name:'Moto',amount:200}]},p1,today,'Trabajo confirmado');
d=saveSalaryPeriod(d,{...p2,earned:true},p2,today,'Trabajo confirmado');
const pay={id:'pay1',configId:'c',date:`${today}T09:00`,amount:400,accountId:'a',method:'Transferencia',reference:'prueba',notes:'',applications:[{periodId:p1.id,conceptId:p1.concepts[0].id,amount:400}],manual:{e:'100'}};
const before=JSON.stringify(d);
d=postSalaryPayment(d,pay,today);
assert.deepEqual(totals(d),{accounts:400,assigned:100,unassigned:300});
assert.deepEqual(salaryPeriodTotals(d,d.salary.periods[0]),{earned:1200,received:400,pending:800,projected:0,status:'Parcial'});
assert.equal(d.movements.length,1);
assert.throws(()=>postSalaryPayment(d,pay,today),/Ya existe un ingreso con estos mismos datos/);
assert.equal(JSON.parse(before).movements.length,0);
const second={...pay,id:'pay2',amount:900,manual:{},applications:[{periodId:p1.id,conceptId:p1.concepts[0].id,amount:600},{periodId:p1.id,conceptId:'moto',amount:200},{periodId:p2.id,conceptId:p2.concepts[0].id,amount:100}]};
d=postSalaryPayment(d,second,today);
assert.equal(salaryPeriodTotals(d,d.salary.periods[0]).status,'Pagado');
assert.equal(salaryPeriodTotals(d,d.salary.periods[1]).pending,900);
const stable=JSON.stringify(d);
assert.throws(()=>postSalaryPayment(d,{...pay,id:'excess',amount:5000,applications:[{periodId:p2.id,conceptId:p2.concepts[0].id,amount:5000}]},today),/supera/);
assert.throws(()=>postSalaryPayment(d,{...pay,id:'bad',amount:300,applications:[{periodId:p2.id,conceptId:p2.concepts[0].id,amount:400}]},today),/completo/);
assert.throws(()=>postSalaryPayment(d,{...pay,id:'distribution',amount:50,manual:{e:'51'},applications:[{periodId:p2.id,conceptId:p2.concepts[0].id,amount:50}]},today));
assert.equal(JSON.stringify(d),stable,'Failed operations never partially apply');
assert.throws(()=>saveSalaryPeriod(d,{...d.salary.periods[0],concepts:[]},d.salary.periods[0],today,'ajuste'),/conceptos/);
assert.throws(()=>saveSalaryPeriod(d,{...d.salary.periods[0],earned:false},d.salary.periods[0],today,'ajuste'),/pagado/);
assert.throws(()=>saveSalaryPeriod(d,{...p2,id:'overlap'},null,today,'ajuste'),/superpone/);
d=saveSalaryConfig(d,{...config,base:2000},config);
assert.equal(d.salary.periods[1].concepts[0].amount,1000,'Config editing preserves prior amounts');
d=generateSalaryPeriods(d,'c',1);
assert.equal(d.salary.periods[3].concepts[0].amount,2000);
assert.equal(new Set(d.salary.periods.map(p=>p.id)).size,4);
const moneyBefore=totals(d),movementsBefore=d.movements.length;
d=unlinkSalaryPayment(d,'pay1','Concepto incorrecto');
assert.deepEqual(totals(d),moneyBefore);
assert.equal(d.movements.length,movementsBefore);
assert.equal(salaryPeriodTotals(d,d.salary.periods[0]).pending,400);
d=postSalaryPayment(d,{...pay,id:'relink',existingMovementId:'salary-income:pay1',manual:{}},today);
assert.deepEqual(totals(d),moneyBefore,'Linking an existing income does not add money');
assert.equal(d.movements.length,movementsBefore);
assert.throws(()=>postSalaryPayment(d,{...pay,id:'duplicate-link',existingMovementId:'salary-income:pay1',manual:{},applications:[{periodId:p2.id,conceptId:p2.concepts[0].id,amount:400}]},today),/Ya existe un ingreso con estos mismos datos/);
const reopened=JSON.parse(JSON.stringify(d));
assert.deepEqual(salaryPeriodTotals(reopened,reopened.salary.periods[0]),salaryPeriodTotals(d,d.salary.periods[0]));
const invalid={...d,movements:d.movements.filter(m=>m.id!=='salary-income:pay1')};
assert.equal(salaryPaymentValid(invalid,invalid.salary.payments.at(-1)),false);
assert.equal(salaryPeriodTotals(invalid,invalid.salary.periods[0]).pending,400);
const reset=resetFinanceData({...d,bank:1300,notifications:{}},{...initial,bank:0,notifications:{}},true);
assert.equal(reset.salary.configs.length,1);assert.equal(reset.salary.payments.length,0);assert.equal(reset.salary.periods.length,0);
for(const value of [d,reopened,reset]){const t=totals(value);assert.equal(t.accounts,t.assigned+t.unassigned);}
const monthly=saveSalaryConfig(initial,{...config,frequency:'Mensual',start:'2028-01-31'},null);
const months=generateSalaryPeriods(monthly,'c',3).salary.periods;
assert.deepEqual(months.map(p=>p.start),['2028-01-31','2028-02-29','2028-03-31']);
assert.throws(()=>saveSalaryPeriod(monthly,{...months[0],earned:true},null,today,'devengo'),/todavía no ha finalizado/);
console.log('OK: salary projections, earned concepts, partial/multiple payments, old debt, atomic distribution, linking without duplicates, corrections, config snapshots, reset, month anchors and JSON persistence.');

// Entry and Salary use the same atomic posting operation.
let entry=saveSalaryConfig(initial,config,null);
assert.throws(()=>saveSalaryConfig(entry,{...config,id:'duplicate',employer:' EJEMPLO   LOCAL ',name:' semanal '},null),/Ya existe un ingreso con estos mismos datos\./);
entry=generateSalaryPeriods(entry,'c',2);
for(const p of entry.salary.periods.slice())entry=saveSalaryPeriod(entry,{...p,earned:true},p,today,'Devengado');
const period=entry.salary.periods[0];
assert.throws(()=>saveSalaryPeriod(entry,{...period,id:'duplicate-period'},null,today,'Intento repetido'),/superpone/);
const input={id:'entry-payment',configId:'c',date:'2026-10-14T09:00',amount:100,accountId:'a',method:'Transferencia',reference:'REF-123',notes:'',name:'Salario semanal',applications:salaryPeriodApplications(entry,'c',period.id,100),manual:{e:'50'}};
entry=postSalaryPayment(entry,input,today);
assert.equal(entry.movements.length,1);assert.equal(entry.movements[0].name,'Salario semanal');assert.equal(salaryPeriodTotals(entry,entry.salary.periods[0]).pending,900);assert.deepEqual(totals(entry),{accounts:100,assigned:50,unassigned:50});
assert.throws(()=>postSalaryPayment(entry,input,today),/Ya existe un ingreso con estos mismos datos/);
assert.throws(()=>postSalaryPayment(entry,{...input,id:'retry-new-id'},today),/Ya existe un ingreso con estos mismos datos/);
entry=postSalaryPayment(entry,{...input,id:'another-date',date:'2026-10-13T09:00',manual:{}},today);
entry=postSalaryPayment(entry,{...input,id:'another-period',applications:salaryPeriodApplications(entry,'c',entry.salary.periods[1].id,100),manual:{}},today);
assert.equal(entry.movements.length,3);assert.equal(entry.salary.payments.length,3);
assert.throws(()=>salaryPeriodApplications(entry,'c',period.id,9999),/supera/);
console.log('OK: Entry integration, normalized config duplicates, period duplicates, partial application, exact-reference retry, legitimate repeated weekly salary and different payment dates.');
