import assert from 'node:assert/strict';
import { reportMovements, financialReport } from '../lib/finance-history.ts';
import { movementFields, movementSign, movementMoney, movementDate } from '../lib/movement-presentation.ts';
import { baseNavigation, nextNavigation, restoreNavigation } from '../lib/app-navigation.ts';
const base={allocations:[],name:'Ingreso',type:'Ingreso',amount:50000};
const items=[{...base,id:'older',date:'2026-10-01T08:00',accountName:'Banco',paymentMethod:'SINPE Móvil',category:'Trabajo',reference:'Semanal',description:'Descripción real'}, {...base,id:'latest',date:'2026-10-12T20:05'}, {...base,id:'outside',date:'2026-10-01T05:59:00Z'}, {...base,id:'expense',type:'Gasto',amount:15000,date:'2026-10-10T12:00',paymentMethod:'Efectivo'}, {...base,id:'transfer',type:'Transferencia',date:'2026-10-11T12:00'}];
const before=JSON.stringify(items);
assert.deepEqual(reportMovements(items,'2026-10','Ingreso').map(m=>m.id),['latest','older']);
assert.deepEqual(reportMovements(items,'2026-10','Gasto').map(m=>m.id),['expense']);
assert.equal(reportMovements(items,'2026-11','Ingreso').length,0);
assert.equal(reportMovements(items,undefined,'Ingreso').length,3);
assert.equal(financialReport(items,'2026-10').income,100000);
const fields=Object.fromEntries(movementFields(items[0]));
assert.equal(fields.Cuenta,'Banco');assert.equal(fields['Medio de recepción'],'SINPE Móvil');assert.equal(fields['Tipo de ingreso'],'Trabajo');assert.equal(fields.Referencia,'Semanal');
assert.equal(Object.fromEntries(movementFields(items[3]))['Método de pago'],'Efectivo');
assert.ok(!Object.hasOwn(Object.fromEntries(movementFields(items[1])),'Cuenta'));
assert.equal(movementSign(items[0]),'+');assert.equal(movementSign(items[3]),'−');assert.equal(movementSign(items[4]),'↔');
assert.match(movementMoney(items[0]),/₡/);assert.match(movementMoney({...items[0],currency:'USD'}),/US\$|USD|\$/);
assert.equal(movementDate('2026-10-12T20:05'),movementDate('2026-10-13T02:05:00Z'));
const report=nextNavigation(baseNavigation('user','session','Reportes'),{reportMonth:'2026-10'});
const list=nextNavigation(report,{reportKind:'Ingreso'});
const detail=nextNavigation(list,{overlay:'movementDetail',context:{movementId:'older'}});
const route=nextNavigation(detail,{overlay:'incomeTrace',context:{movementId:'older'}});
assert.equal(route.value.reportMonth,'2026-10');assert.equal(route.value.reportKind,'Ingreso');assert.equal(restoreNavigation(detail,'user','session').replace,false);
assert.equal(nextNavigation(route,{view:'Inicio',overlay:null}).value.reportKind,null);
assert.equal(JSON.stringify(items),before);
console.log('OK: reportes filtrados y ordenados, detalles reales, signos, moneda, zona CR, vacío, navegación y datos inmutables.');
