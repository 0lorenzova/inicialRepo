import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {canConfirmSalaryPeriod,salaryWorkEnd} from '../lib/salary-dates.ts';
import {saveSalaryConfig,salaryPeriodForDate,postSalaryPayment,salaryPeriodPresentation,salaryPaymentTiming} from '../lib/salary-tracking.ts';
const config={id:'c',employer:'Prueba',name:'Salario',currency:'CRC',base:100,frequency:'Semanal',calendarMode:'iso-workdays',start:'2026-10-12',payOffset:3,workDays:[1,2,3,4,5],active:true};
const ledger=saveSalaryConfig({accounts:[{id:'a',name:'Ficticia',type:'Banco',active:true,balance:0}],envelopes:[],movements:[],loans:[]},config,null);
const period=salaryPeriodForDate(ledger,'c','2026-10-16'),before=JSON.stringify(ledger);
assert.equal(salaryWorkEnd(period),'2026-10-16');
assert.equal(period.payDate,'2026-10-19');
assert.equal(salaryPaymentTiming(period,'2026-10-16').laborAdvance,true);
assert.equal(salaryPaymentTiming(period,'2026-10-17').laborAdvance,false);
assert.equal(salaryPaymentTiming(period,'2026-10-17').kind,'early');
assert.equal(salaryPaymentTiming(period,'2026-10-19').kind,'on-time');
assert.equal(salaryPaymentTiming(period,'2026-10-20').kind,'late');
assert.equal(salaryWorkEnd({...period,scheduledWorkDays:[6]}),'2026-10-17');
assert.equal(salaryWorkEnd({...period,scheduledWorkDays:undefined}),period.end);
assert.equal(salaryPeriodPresentation(ledger,period,'2026-10-17').workState,'Jornada prevista finalizada');
assert.equal(salaryPeriodPresentation(ledger,{...period,payDate:'2026-10-10'},'2026-10-11').tone,'neutral','Future unearned work must not turn red even with an inconsistent early due date');
assert.equal(JSON.stringify(ledger),before);
const payment={id:'p',configId:'c',date:'2026-10-16T08:00',amount:100,accountId:'a',method:'Efectivo',reference:'',notes:'',preparedPeriod:period,applications:[{periodId:period.id,conceptId:period.concepts[0].id,amount:100}]};
const paid=postSalaryPayment(ledger,payment,'2026-10-16'),view=salaryPeriodPresentation(paid,period,'2026-10-16');
assert.equal(view.tone,'paid');assert.equal(view.workState,'En curso');assert.equal(view.laborAdvances,100);assert.equal(view.early,100);assert.equal(paid.salary.periods[0].earned,false);
const afterWork=postSalaryPayment(ledger,{...payment,date:'2026-10-17T08:00'},'2026-10-17');
const second=salaryPeriodPresentation(afterWork,period,'2026-10-17');assert.equal(second.laborAdvances,0);assert.equal(second.early,100);
const css=readFileSync(new URL('../components/salary-status.module.css',import.meta.url),'utf8');
assert.match(css,/data-tone=partial\]\{--salary-bg:#fff0ad/);assert.match(css,/data-tone=neutral\]\{--salary-bg:#e6eaf0/);
const calendar=readFileSync(new URL('../components/salary-receive-dialog.module.css',import.meta.url),'utf8');assert.match(calendar,/statusDot.partial\{background:#facc15/);assert.match(calendar,/statusDot.neutral\{background:#94a3b8/);
console.log('OK: work schedule snapshots, Friday/Saturday distinction, advance versus due date, full advance without earned work, legacy fallback, future neutral, shared palette and no consultation writes.');

const sameDayPeriod={...period,payDate:'2026-10-16'};
const sameDay=postSalaryPayment(ledger,{...payment,preparedPeriod:sameDayPeriod},'2026-10-16');
const sameDayView=salaryPeriodPresentation(sameDay,sameDayPeriod,'2026-10-16');
assert.equal(sameDayView.early,0);assert.equal(sameDayView.laborAdvances,100);assert.equal(sameDayView.hasAdvance,true);
assert.equal(second.hasAdvance,true);
assert.equal(salaryPeriodPresentation(ledger,period,'2026-10-16').hasAdvance,false);
console.log('OK: advance filter includes labor advances on the expected payment date and excludes periods without receipts.');

assert.equal(canConfirmSalaryPeriod(period,'2026-10-16'),false);
assert.equal(canConfirmSalaryPeriod(period,'2026-10-17'),true);
assert.equal(canConfirmSalaryPeriod({...period,scheduledWorkDays:undefined},'2026-10-17'),false);
assert.equal(canConfirmSalaryPeriod({...period,scheduledWorkDays:[0]},'2026-10-18'),false);
assert.equal(canConfirmSalaryPeriod({...period,scheduledWorkDays:[0]},'2026-10-19'),true);
console.log('OK: earned guard follows saved last workday; legacy and Sunday schedules remain protected.');
