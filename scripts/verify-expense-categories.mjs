import assert from 'node:assert/strict';
import { defaultExpenseCategories, expenseCategories, saveExpenseCategory } from '../lib/expense-categories.ts';
assert.equal(expenseCategories().length,10);assert.deepEqual(expenseCategories([]),[]);
const before=JSON.stringify(defaultExpenseCategories);
const category={id:'travel',name:'  Viajes   familiares ',archived:false};
const added=saveExpenseCategory(defaultExpenseCategories,category,null);
assert.equal(added.at(-1).name,'Viajes familiares');assert.equal(JSON.stringify(defaultExpenseCategories),before);
assert.throws(()=>saveExpenseCategory(added,{...category,name:'viajes familiares'},null));
assert.throws(()=>saveExpenseCategory(added,{...category,id:'other',name:'ALIMENTACION'},null));
assert.throws(()=>saveExpenseCategory(added,{...category,id:'other',name:'Sin categoría'},null));
assert.throws(()=>saveExpenseCategory(added,{...category,id:'other',name:'  '},null));
const original=added.at(-1);
const renamed=saveExpenseCategory(added,{...original,name:'Vacaciones'},original);
assert.equal(renamed.at(-1).id,original.id);
assert.throws(()=>saveExpenseCategory(renamed,{...original,name:'Otro'},original));
const archived=saveExpenseCategory(renamed,{...renamed.at(-1),archived:true},renamed.at(-1));
assert.equal(archived.at(-1).archived,true);
const restored=saveExpenseCategory(archived,{...archived.at(-1),archived:false},archived.at(-1));
assert.deepEqual(restored,renamed);
const historical={category:'Viajes familiares',amount:500};
assert.deepEqual(historical,{category:'Viajes familiares',amount:500});
assert.deepEqual(JSON.parse(JSON.stringify(restored)),restored);
console.log('OK: category defaults, normalized names, duplicates, stale edit, archive/restore, stable identity and unchanged historical snapshots.');
