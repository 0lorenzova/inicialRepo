import assert from 'node:assert/strict';
import { calendarDays, calendarEntries, calendarRange, shiftCalendar } from '../lib/planning-calendar.ts';
import { moveEnvelopeGoal } from '../lib/move-envelope-goal.ts';
import { planningItems } from '../lib/envelope-planning.ts';
assert.equal(calendarDays('2024-02-29').dates.length,29);
assert.equal(calendarDays('2026-02-01').offset,6);
assert.deepEqual(calendarRange('2026-01-01','Semana'),{from:'2025-12-29',to:'2026-01-04'});
assert.deepEqual(calendarRange('2026-10-07','Año'),{from:'2026-01-01',to:'2026-12-31'});
assert.equal(shiftCalendar('2026-01-31','Mes',1),'2026-02-01');
const source={id:'a',name:'Origen',balance:200,goal:1000,goalEnabled:true,goalDate:'2026-10-20',goalThresholds:{green:15,yellow:8,red:5},recurrence:{amount:100,frequency:'Mensual',nextDate:'2026-10-10',snoozedUntil:'2026-10-15'}};
const target={id:'b',name:'Destino',balance:500};
const item={id:'s',name:'Importe',amount:10,deadline:'2026-10-10',active:true,timingEnabled:true};
const envelopes=[{...source,scheduledAmounts:[item,{...item,id:'paid',payment:{amount:10,date:'2026-10-07',accountId:'a',movementId:'m'}}]},target];
const original=JSON.stringify(envelopes);
const events=calendarEntries(envelopes,'2026-10-07');
assert.equal(events.length,3);assert.equal(events.find(e=>!e.item).date,'2026-10-15');
assert.equal(calendarEntries([{...source,archived:true}],'2026-10-07').length,0);
const moved=moveEnvelopeGoal(envelopes,envelopes[0],'b','stable-goal');
assert.equal(JSON.stringify(envelopes),original);
assert.equal(moved[0].goal,undefined);assert.equal(moved[1].goalId,'stable-goal');
assert.equal(moved[1].goalName,'Meta de Origen');assert.equal(moved[1].balance,500);
assert.deepEqual(moved[0].recurrence,source.recurrence);assert.equal(moved[1].recurrence,undefined);
assert.equal(planningItems(moved[1],'2026-10-07')[0].id,'stable-goal');
assert.equal(calendarEntries(moved,'2026-10-07').filter(e=>e.item?.kind==='goal')[0].envelopeId,'b');
const withRecurrence=moveEnvelopeGoal(envelopes,envelopes[0],'b','stable-goal',true);
assert.equal(withRecurrence[0].recurrence,undefined);assert.deepEqual(withRecurrence[1].recurrence,source.recurrence);
assert.throws(()=>moveEnvelopeGoal(moved,envelopes[0],'b','duplicate'));
assert.throws(()=>moveEnvelopeGoal([source,{...target,goal:50,goalEnabled:false}],source,'b','x'));
assert.throws(()=>moveEnvelopeGoal([source,{...target,recurrence:source.recurrence}],source,'b','x',true));
assert.throws(()=>moveEnvelopeGoal([{...source,goal:1500},target],source,'b','x'));
const roundTrip=moveEnvelopeGoal(moved,moved[1],'a','unused');assert.equal(roundTrip[0].goalId,'stable-goal');
assert.equal(JSON.stringify(envelopes),original);
console.log('OK: calendar leap/year/week boundaries, shared schedules, snoozing, paid exclusion; stable goal move, optional recurrence, no balance change or overwritten goals.');

const {interfaceScale,nextInterfaceSize,normalizeInterfaceSize}=await import('../lib/interface-size.ts');
assert.deepEqual([0,1,2].map(interfaceScale),[1,1.12,1.25]);
assert.equal(nextInterfaceSize(nextInterfaceSize(nextInterfaceSize(0))),0);
assert.equal(normalizeInterfaceSize('2'),2);assert.equal(normalizeInterfaceSize('unknown'),0);
console.log('OK: interface sizing levels, cycle and persisted normalization.');

assert.equal(calendarRange("9999-12-31","Semana").to,"9999-12-31");
