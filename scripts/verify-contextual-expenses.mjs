import assert from 'node:assert/strict';
import {associateExpenseCategory,saveExpenseCategory,categoriesForEnvelope} from '../lib/expense-categories.ts';
import {classifyExpense,validateExpenseClassification} from '../lib/expense-classification.ts';
import {postMovement,totals} from '../lib/finance-ledger.ts';
import {financialReport} from '../lib/finance-history.ts';
import {baseNavigation,nextNavigation,restoreNavigation} from '../lib/app-navigation.ts';

let categories=[{id:'food',name:'Restaurantes',archived:false},{id:'travel',name:'Paseos',archived:false}];
categories=associateExpenseCategory(categories,'food','home');
categories=associateExpenseCategory(categories,'food','home');
categories=associateExpenseCategory(categories,'travel','home');
categories=associateExpenseCategory(categories,'travel','savings');
assert.equal(categoriesForEnvelope(categories,'home').length,2);
assert.deepEqual(categories[0].envelopeIds,['home']);
const allocations=[{id:'home',amount:2000},{id:'savings',amount:500}];
const drafts={home:{food:'1500',travel:'500'},savings:{travel:''}};
const classification=classifyExpense(2500,allocations,drafts,categories);
assert.deepEqual(classification.map(item=>item.amount),[1500,500,500]);
assert.throws(()=>classifyExpense(2500,[{id:'home',amount:2000}],drafts,categories),/exactamente/);
assert.throws(()=>classifyExpense(2500,allocations,{home:{food:'2000',travel:'2000'}},categories),/suma/);
assert.throws(()=>classifyExpense(2500,allocations,{home:{food:'',travel:''}},categories),/entero/);
assert.throws(()=>classifyExpense(2500,allocations,{savings:{food:''}},categories),/disponible/);
assert.throws(()=>validateExpenseClassification([...classification,classification[0]],2500,allocations),/duplicadas/);
assert.throws(()=>validateExpenseClassification([{name:'Sin categoría',amount:2500,envelopeId:'foreign'}],2500,allocations),/exactamente/);
assert.deepEqual(classifyExpense(2500,[],{},categories),[{name:'Sin categoría',amount:2500}]);
const ledger={accounts:[{id:'bank',name:'Banco',type:'Banco',balance:5000,active:true}],envelopes:[{id:'home',name:'Hogar',balance:3000},{id:'savings',name:'Ahorro',balance:1000}],loans:[],movements:[]};
const before=JSON.stringify(ledger);
const input={id:'expense-one',type:'Gasto',amount:2500,accountId:'bank',envelopeAllocations:allocations,date:'2026-10-11T12:00',name:'Gasto local',categoryAllocations:classification};
const posted=postMovement(ledger,input);
assert.equal(JSON.stringify(ledger),before);
assert.equal(posted.movements.length,1);
assert.equal(financialReport(posted.movements).spent,2500);
assert.deepEqual(financialReport(posted.movements).categories,[['Restaurantes',1500],['Paseos',1000]]);
assert.deepEqual(totals(posted),{accounts:2500,assigned:1500,unassigned:1000});
assert.deepEqual(posted.envelopes.map(item=>item.balance),[1000,500]);
assert.throws(()=>postMovement(posted,input),/existe|saldo/);
assert.throws(()=>postMovement(ledger,{...input,categoryAllocations:classification.map(item=>({...item,amount:2500}))}));
const snapshot=JSON.stringify(posted.movements);
categories=saveExpenseCategory(categories,{...categories[0],name:'Comidas afuera'},categories[0]);
assert.deepEqual(categories[0].envelopeIds,['home']);
assert.equal(JSON.stringify(posted.movements),snapshot);
assert.equal(posted.movements[0].categoryAllocations[0].name,'Restaurantes');
assert.deepEqual(JSON.parse(JSON.stringify(posted)).movements[0].categoryAllocations,classification);
const archived=saveExpenseCategory(categories,{...categories[0],archived:true},categories[0]);
assert.throws(()=>classifyExpense(2500,allocations,drafts,archived),/disponible/);
const base=baseNavigation('local','session','Sin asignar');
const trace=nextNavigation(base,{overlay:'incomeTrace',context:{movementId:'income',expanded:['home']}});
const history=nextNavigation(trace,{view:'Movimientos',overlay:null,movementEnvelopeId:'home',returnToIncome:'income'});
assert.equal(history.value.returnToIncome,'income');
assert.equal(restoreNavigation(trace,'local','session').entry.value.context.expanded[0],'home');
assert.equal(nextNavigation(history,{view:'Inicio'}).value.returnToIncome,null);
assert.equal(restoreNavigation(nextNavigation(base,{overlay:'expenseCategories',context:{envelopeId:'home'}}),'local','session').replace,false);
console.log('OK: category associations, explicit splits, invalid and duplicate amounts, one atomic expense, stable historical snapshots, persistence and contextual navigation.');
