import assert from "node:assert/strict";
import { fundingOptions, fundingKey, incomeDistribution, postDistributedIncome } from "../lib/income-distribution.ts";
import { planningTone, proximityCounts, globalPlanningItems } from "../lib/envelope-planning.ts";
import { totals } from "../lib/finance-ledger.ts";
import { calendarEntries, calendarEntryTone } from "../lib/planning-calendar.ts";
const today="2026-10-07";
const payment=(id,deadline,amount=1000)=>({id,name:id,deadline,amount,active:true,timingEnabled:true});
const envelopes=[
  {id:"home",name:"Hogar",balance:0,scheduledAmounts:[payment("white","2027-01-01"),payment("red",today),payment("purple","2026-10-06"),payment("yellow","2026-10-14"),payment("green","2026-10-20"),{...payment("paid",today),payment:{movementId:"old",amount:1000,date:today,accountId:"a"}}]},
  {id:"save",name:"Ahorro",balance:500,goal:10000,goalEnabled:true,goalId:"goal",goalName:"Meta",goalDate:"2026-12-01"},
  {id:"archive",name:"Archivado",balance:0,archived:true,scheduledAmounts:[payment("archived",today)]},
];
const ledger={accounts:[{id:"a",name:"Banco",type:"Banco",balance:500,active:true}],envelopes,loans:[],movements:[]};
const original=JSON.stringify(ledger);
const options=fundingOptions(envelopes,today);
assert.equal(options.length,6);
assert.deepEqual(options.map(option=>option.item.id),["purple","red","yellow","green","goal","white"]);
for(const option of options) assert.equal(planningTone(option.item),planningTone(globalPlanningItems(envelopes,today).find(item=>item.envelopeId===option.envelopeId&&item.item.id===option.item.id).item));
const calendar=calendarEntries(envelopes,today);
for(const entry of calendar)assert.equal(calendarEntryTone(entry,today),planningTone(options.find(option=>option.envelopeId===entry.envelopeId&&option.item.id===entry.item.id).item));
assert.equal(calendarEntryTone({date:today},today),"red");
assert.equal(calendarEntryTone({date:"2026-10-06"},today),"purple");
const choose=id=>options.find(option=>option.item.id===id).selection;
let selections=[choose("purple")];
let plan=incomeDistribution(envelopes,today,5000,{},selections);
assert.equal(plan.remaining,4000);
selections=[...selections,choose("red")];
plan=incomeDistribution(envelopes,today,5000,{save:"500"},selections);
assert.equal(plan.selected,2000);assert.equal(plan.total,2500);assert.equal(plan.remaining,2500);
selections=selections.filter(item=>fundingKey(item)!==fundingKey(choose("purple")));
assert.equal(incomeDistribution(envelopes,today,5000,{},selections).remaining,4000);
assert.equal(JSON.stringify(ledger),original,"Provisional selection never writes ledger");
const input={id:"income-1",accountId:"a",amount:5000,date:`${today}T10:00`,name:"Ingreso de prueba"};
const beforeCounts=proximityCounts(globalPlanningItems(envelopes,today).map(entry=>entry.item));
const next=postDistributedIncome(ledger,input,today,{save:"500"},[choose("purple"),choose("red")]);
assert.deepEqual(totals(next),{accounts:5500,assigned:3000,unassigned:2500});
assert.equal(next.movements.length,1);assert.equal(next.movements[0].type,"Ingreso");
assert.equal(next.movements[0].fundingTargets.length,2);
assert.equal(next.envelopes[0].balance,2000);assert.equal(next.envelopes[1].balance,1000);
assert.deepEqual(next.envelopes[0].scheduledAmounts,envelopes[0].scheduledAmounts,"Assignment is not payment");
assert.deepEqual(proximityCounts(globalPlanningItems(next.envelopes,today).map(entry=>entry.item)),beforeCounts);
assert.equal(JSON.stringify(ledger),original,"Atomic write preserves original");
assert.throws(()=>postDistributedIncome(next,input,today,{},[]),/ya existe/);
assert.throws(()=>postDistributedIncome(ledger,{...input,amount:999},today,{},[choose("red")]),/supera/);
assert.throws(()=>postDistributedIncome(ledger,input,today,{},[choose("red"),choose("red")]),/más de una vez/);
for(const value of ["-1","1.5","NaN","Infinity"])assert.ok(incomeDistribution(envelopes,today,5000,{home:value},[]).errors.length);
const changed=structuredClone(ledger);changed.envelopes[0].scheduledAmounts.find(item=>item.id==="red").amount=900;
assert.throws(()=>postDistributedIncome(changed,input,today,{},[choose("red")]),/cambió/);
changed.envelopes[0].scheduledAmounts.find(item=>item.id==="red").amount=1000;
changed.envelopes[0].scheduledAmounts.find(item=>item.id==="red").payment={movementId:"new",amount:1000,date:today,accountId:"a"};
assert.throws(()=>postDistributedIncome(changed,input,today,{},[choose("red")]),/pendiente/);
changed.envelopes[0].archived=true;
assert.throws(()=>postDistributedIncome(changed,input,today,{home:"100"},[]),/activo/);
const restored=JSON.parse(JSON.stringify(next));
assert.deepEqual(totals(restored),totals(next));assert.deepEqual(restored.movements[0].fundingTargets,next.movements[0].fundingTargets);
const unassigned=postDistributedIncome(ledger,input,today,{},[]);
assert.equal(totals(unassigned).unassigned,5000);
assert.equal(totals(next).accounts,totals(next).assigned+totals(next).unassigned);
console.log("OK: selección compartida, cinco estados, provisión sin escrituras, montos, confirmación atómica, duplicados, cambios concurrentes, fondos sin pagar, historial y persistencia.");
