import assert from 'node:assert/strict';
import { addFinanceAccount } from '../lib/finance-accounts.ts';
import { moveScheduledAmount, payScheduledAmount } from '../lib/envelope-planning.ts';
import { totals } from '../lib/finance-ledger.ts';
const accounts=addFinanceAccount([],{id:'a',name:' Cuenta prueba ',type:'Banco'});
assert.equal(accounts[0].balance,0);assert.equal(accounts[0].name,'Cuenta prueba');
assert.throws(()=>addFinanceAccount(accounts,{id:'a',name:'Duplicada',type:'Banco'}));
assert.throws(()=>addFinanceAccount(accounts,{id:'b',name:' ',type:'Banco'}));
assert.throws(()=>addFinanceAccount(accounts,{id:'b',name:'X',type:'No válido'}));
const item={id:'p',name:'Mensual',amount:100,deadline:'2026-10-05',active:true,timingEnabled:true,thresholds:{green:15,yellow:8,red:5},repetition:{frequency:'monthly',anchorDay:5,seriesId:'s'}};
const envelopes=[{id:'source',name:'Origen',balance:200,scheduledAmounts:[item]},{id:'target',name:'Destino',balance:300}];
const snapshot=JSON.stringify(envelopes);
const moved=moveScheduledAmount(envelopes,'source','target',item);
assert.equal(JSON.stringify(envelopes),snapshot);
assert.equal(moved[0].scheduledAmounts.length,0);assert.deepEqual(moved[1].scheduledAmounts[0],item);
assert.deepEqual(moved.map(e=>e.balance),[200,300]);
assert.throws(()=>moveScheduledAmount(moved,'source','target',item));
assert.throws(()=>moveScheduledAmount(envelopes,'source','source',item));
assert.throws(()=>moveScheduledAmount(envelopes,'source','missing',item));
assert.throws(()=>moveScheduledAmount(envelopes,'source','target',{...item,amount:200}));
const ledger={accounts:[{...accounts[0],balance:1000}],envelopes:moved,loans:[],movements:[]};
const paid=payScheduledAmount(ledger,'target','p',100,'a','2026-10-05T12:00');
assert.equal(paid.envelopes[0].balance,200);assert.equal(paid.envelopes[1].balance,200);
assert.equal(paid.accounts[0].balance,900);assert.equal(paid.movements.length,1);
assert.equal(paid.envelopes[1].scheduledAmounts[1].deadline,'2026-11-05');
assert.throws(()=>moveScheduledAmount(paid.envelopes,'target','source',item));
const summary=totals(paid);assert.equal(summary.accounts,summary.assigned+summary.unassigned);
console.log('OK: zero-balance account creation; atomic planning move, recurrence, payment at destination, stale/paid/duplicate protection.');
