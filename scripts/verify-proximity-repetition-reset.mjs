import assert from 'node:assert/strict';
import { DEFAULT_GOAL_THRESHOLDS, compactTemporalDistance } from '../lib/envelope-goals.ts';
import { planningItems, planningTone, proximityCounts, globalPlanningItems, nextScheduledDate, payScheduledAmount, validateScheduledAmount } from '../lib/envelope-planning.ts';
import { resetFinanceData } from '../lib/finance-reset.ts';
import { normalizeNotificationState } from '../lib/finance-notifications.ts';
import { postMovement, totals } from '../lib/finance-ledger.ts';
const today='2026-10-03';
assert.deepEqual(DEFAULT_GOAL_THRESHOLDS,{green:15,yellow:8,red:5});
const base={name:'Prueba',amount:100,active:true,timingEnabled:true,thresholds:DEFAULT_GOAL_THRESHOLDS};
const dates=['2026-12-03','2026-10-16','2026-10-10','2026-10-05','2026-10-02','2026-09-12'];
const envelope={id:'e',name:'Sobre',balance:0,scheduledAmounts:dates.map((deadline,i)=>({...base,id:String(i),deadline}))};
const states=planningItems(envelope,today);
assert.deepEqual(dates.map((d,i)=>planningTone(states.find(p=>p.id===String(i)))),['white','green','yellow','red','purple','purple']);
assert.equal(compactTemporalDistance('2026-10-02',today),'1 día');
assert.equal(compactTemporalDistance('2026-09-12',today),'21 días');
assert.equal(compactTemporalDistance('2026-10-03',today),'0 días');
assert.equal(compactTemporalDistance('2026-11-03',today),'31 días');
assert.equal(compactTemporalDistance('2026-12-03',today),'61 días');
assert.match(states.find(p=>p.id==='4').temporal.explanation,/pasó hace 1 día/);
envelope.scheduledAmounts.push({...base,id:'green2',deadline:'2026-10-17'});
assert.deepEqual(proximityCounts(planningItems(envelope,today)),{white:1,green:2,yellow:1,red:1,purple:2});
const plain={...envelope,id:'plain',scheduledAmounts:[{...base,id:'missing-config',deadline:'2026-10-04',thresholds:undefined},{...base,id:'disabled',deadline:'2026-10-02',timingEnabled:false}]};
assert.deepEqual(proximityCounts(planningItems(plain,today)),{white:0,green:0,yellow:0,red:1,purple:1});
assert.deepEqual(planningItems(plain,today).map(planningTone),['purple','red']);
validateScheduledAmount({...base,id:'off',deadline:today,timingEnabled:false,thresholds:{green:NaN,yellow:NaN,red:NaN}});
for(const tone of ['white','green','yellow','red','purple']) {
 const result=globalPlanningItems([envelope,plain],today,tone);
 assert.ok(result.length>0);
 assert.ok(result.every(p=>planningTone(p.item)===tone));
 assert.deepEqual(result.map(p=>p.item.deadline),result.map(p=>p.item.deadline).sort());
}
assert.equal(globalPlanningItems([envelope,plain],today).length,9);
assert.equal(globalPlanningItems([{...envelope,archived:true}],today).length,0);
for (const [frequency,date,expected] of [['daily','2026-12-31','2027-01-01'],['weekly','2026-12-31','2027-01-07'],['monthly','2026-01-15','2026-02-15'],['monthly','2026-01-31','2026-02-28'],['monthly','2028-01-31','2028-02-29'],['monthly','2026-03-31','2026-04-30']]) {
 const scheduled={...base,id:'repeat',deadline:date,repetition:{frequency,anchorDay:Number(date.slice(8)),seriesId:'series'}};
 assert.equal(nextScheduledDate(scheduled),expected);
 if(date.endsWith('01-31')) assert.equal(nextScheduledDate({...scheduled,deadline:expected}),date.slice(0,4)+'-03-31');
}
const repeat={...base,id:'repeat',deadline:'2026-01-31',repetition:{frequency:'monthly',anchorDay:31,seriesId:'s'}};
const initial={bank:0,notifications:normalizeNotificationState(),accounts:[{id:'a',name:'Banco',type:'Banco',balance:0,active:true}],envelopes:[{id:'e',name:'Sobre',balance:0}],loans:[],movements:[],hidden:false};
let ledger=postMovement({...initial,envelopes:[{...envelope,scheduledAmounts:[repeat],balanceHidden:true,goal:500,goalName:'Meta'}]},{id:'income',type:'Ingreso',amount:1000,accountId:'a',envelopeAllocations:[{id:'e',amount:1000}],date:'2026-01-01T09:00',name:'Ficticio'});
const before=structuredClone(ledger);
assert.throws(()=>payScheduledAmount(ledger,'e','repeat',2000,'a','2026-01-31T09:00'),/suficiente/);
assert.deepEqual(ledger,before);
ledger=payScheduledAmount(ledger,'e','repeat',100,'a','2026-01-31T09:00');
assert.equal(ledger.envelopes[0].scheduledAmounts.length,2);
const next=ledger.envelopes[0].scheduledAmounts.find(p=>!p.payment);
assert.equal(next.deadline,'2026-02-28');
assert.equal(next.repetition.anchorDay,31);
assert.throws(()=>payScheduledAmount(ledger,'e','repeat',100,'a','2026-01-31T09:00'),/pagado/);
ledger=payScheduledAmount(ledger,'e',next.id,100,'a','2026-02-28T09:00');
assert.equal(ledger.envelopes[0].scheduledAmounts.find(p=>!p.payment).deadline,'2026-03-31');
assert.equal(totals(ledger).accounts,totals(ledger).assigned+totals(ledger).unassigned);
const data={...ledger,bank:800,notifications:{...normalizeNotificationState(),sound:true,readIds:['old'],deliveredIds:['old'],dismissedIds:['old']},hidden:true,envelopesGridColumns:3,summaryPinned:true};
const copy=structuredClone(data), kept=resetFinanceData(data,initial,true);
assert.deepEqual(data,copy);
assert.deepEqual(totals(kept),{accounts:0,assigned:0,unassigned:0});
assert.equal(kept.movements.length,0);assert.equal(kept.loans.length,0);
assert.equal(kept.hidden,true);assert.equal(kept.envelopesGridColumns,3);assert.equal(kept.summaryPinned,true);
assert.equal(kept.envelopes[0].balanceHidden,true);assert.equal(kept.envelopes[0].goal,500);
assert.equal(kept.envelopes[0].scheduledAmounts.length,1);assert.equal(kept.envelopes[0].scheduledAmounts[0].payment,undefined);
assert.equal(kept.notifications.sound,true);assert.deepEqual(kept.notifications.readIds,[]);
assert.deepEqual(resetFinanceData(data,initial,false),initial);
console.log('OK A-Q: five states, compact distance, counts, five global filters + all, recurrence calendar/leap years, atomic payment and duplicates, both reset modes and preservation.');
