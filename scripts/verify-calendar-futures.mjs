import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {calendarEntries,calendarRange} from "../lib/planning-calendar.ts";
import {planningItems,planningIndicatorGroups,saveScheduledAmount,payScheduledAmount} from "../lib/envelope-planning.ts";
import {recurrenceDates,confirmRecurringContribution} from "../lib/finance-recurrence.ts";
const today="2026-01-01", window=calendarRange("2026-03-01","Mes");
const item={id:"one",name:"Electricidad",amount:100,deadline:"2026-01-31",active:true,timingEnabled:true,repetition:{frequency:"monthly",anchorDay:31,seriesId:"power"}};
const seed={id:"home",name:"Hogar",balance:1000,scheduledAmounts:[item],goal:500,goalDate:"2026-03-05",recurrence:{amount:200,frequency:"Mensual",nextDate:"2026-01-31"}};
const before=JSON.stringify(seed);
let events=calendarEntries([seed],today,window);
assert.equal(events.filter(e=>e.virtual&&e.date==="2026-03-31").length,2);
assert.equal(events.filter(e=>e.item?.kind==="goal").length,0,"An already reached goal is not shown as a pending calendar item");
assert.ok(events.filter(e=>e.virtual).every(e=>e.recurrent&&!e.item?.payment&&e.item?.covered===undefined));
assert.equal(JSON.stringify(seed),before,"Consultation never writes to stored data");
assert.equal(new Set(events.map(e=>e.key)).size,events.length);
assert.deepEqual(calendarEntries([seed],today,window),events,"Navigating back does not duplicate occurrences");
assert.equal(calendarEntries([seed],today,calendarRange("2026-02-01","Mes")).filter(e=>e.virtual&&e.date==="2026-02-28").length,2);
const changed={...item,id:"scheduled:power:2026-02-28",occurrenceDate:"2026-02-28",deadline:"2026-03-02",amount:150};
const exceptions={...seed,scheduledAmounts:[item,changed]};
events=calendarEntries([exceptions],today,calendarRange("2026-02-01","Mes"));
assert.equal(events.filter(e=>e.item&&e.date==="2026-02-28").length,0,"Edited occurrence replaces its nominal date");
assert.equal(events.find(e=>e.item?.id===changed.id).amount,150);
assert.equal(calendarEntries([exceptions],today,window).find(e=>e.virtual&&e.item&&e.date==="2026-03-31").amount,150);
const edited=saveScheduledAmount([seed],seed.id,{...item,deadline:"2026-02-02"},item)[0].scheduledAmounts[0];
assert.equal(edited.occurrenceDate,"2026-01-31");
const ended={...seed,scheduledAmounts:[{...item,repetition:{...item.repetition,endDate:"2026-02-28"}}],recurrence:{...seed.recurrence,endDate:"2026-02-28"}};
assert.equal(calendarEntries([ended],today,window).filter(e=>e.virtual).length,0);
assert.deepEqual(recurrenceDates("2024-02-29","2028-01-01","2028-12-31",{unit:"months",amount:12},29),["2028-02-29"]);
assert.equal(recurrenceDates("2026-01-05","2026-03-01","2026-03-31",{unit:"days",amount:7}).length,5);
assert.equal(recurrenceDates("2026-01-01","2026-03-01","2026-03-31",{unit:"days",amount:15}).length,2);
assert.equal(recurrenceDates("2026-01-01","9999-12-01","9999-12-31",{unit:"days",amount:1}).length,31,"Far periods jump directly");
assert.equal(calendarEntries([{...seed,archived:true}],today,window).length,0);
const ledger={accounts:[{id:"a",name:"Banco",type:"Banco",active:true,balance:3000}],envelopes:[seed],loans:[],movements:[]};
const paid=payScheduledAmount({...ledger,envelopes:[ended]},"home","one",100,"a","2026-01-31T10:00");
const second=paid.envelopes[0].scheduledAmounts[1];
assert.equal(second.deadline,"2026-02-28");
assert.equal(payScheduledAmount(paid,"home",second.id,100,"a","2026-02-28T10:00").envelopes[0].scheduledAmounts.length,2);
let contributions=confirmRecurringContribution(ledger,"home","2026-01-31","2026-01-31T10:00");
contributions=confirmRecurringContribution(contributions,"home","2026-02-28","2026-02-28T10:00");
assert.equal(contributions.envelopes[0].recurrence.nextDate,"2026-03-31","Actual recurrence and projection share the same anchor");
const variants=[{...item,id:"purple",deadline:"2025-12-01"},{...item,id:"both",deadline:"2025-12-01",plannedPaymentDate:"2025-12-02"},{...item,id:"late",deadline:"2026-01-10",plannedPaymentDate:"2026-01-11"}];
const groups=planningIndicatorGroups(planningItems({...seed,goalEnabled:false,scheduledAmounts:variants},today));
assert.equal(groups.filter(g=>g.tone==="purple").length,2);
assert.equal(groups.filter(g=>g.late).length,2);
const css=readFileSync(new URL('../components/temporal-indicator.module.css',import.meta.url),'utf8');
assert.match(css,/paymentTurn 2000ms linear infinite/);
assert.match(css,/blinkThenTurn 4000ms linear infinite/);
assert.match(css,/50% \{ opacity:1; transform:perspective\(80px\) rotateY\(0deg\)/);
assert.match(css,/100% \{ opacity:1; transform:perspective\(80px\) rotateY\(360deg\)/);
assert.match(css,/prefers-reduced-motion: reduce/);
console.log('OK: bounded virtual recurrences, frequencies/leap dates/end dates/edited occurrences, shared month anchor, no financial writes, warning separation and 2000ms rotation phase.');
