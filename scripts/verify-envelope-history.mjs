import assert from 'node:assert/strict';
import {assign,unassign,transfer,lend,repay,postMovement} from '../lib/finance-ledger.ts';
import {envelopeMovementEffect,envelopeHistorySections,filterHistory} from '../lib/finance-history.ts';
let ledger={accounts:[{id:'a',name:'Cuenta',balance:0,type:'Banco',active:true}],envelopes:[{id:'h',name:'Hogar',balance:0},{id:'s',name:'Ahorro',balance:0}],movements:[],loans:[]};
const date='2026-10-11T10:00';
ledger=postMovement(ledger,{id:'income',type:'Ingreso',name:'Ingreso',amount:10000,date,accountId:'a',envelopeAllocations:[{id:'h',amount:4000},{id:'s',amount:2000}]});
assert.equal(envelopeMovementEffect(ledger.movements[0],'h'),4000);
ledger=postMovement(ledger,{id:'expense',type:'Gasto',name:'Gasto',amount:1000,date,accountId:'a',envelopeAllocations:[{id:'h',amount:600},{id:'s',amount:400}]});
assert.equal(envelopeMovementEffect(ledger.movements[0],'h'),-600);
ledger=assign(ledger,'h',500,date,'assign');assert.equal(envelopeMovementEffect(ledger.movements[0],'h'),500);
ledger=unassign(ledger,'h',100,date,'unassign');assert.equal(envelopeMovementEffect(ledger.movements[0],'h'),-100);
ledger=transfer(ledger,'h','s',200,date,'transfer');
assert.equal(envelopeMovementEffect(ledger.movements[0],'h'),-200);assert.equal(envelopeMovementEffect(ledger.movements[0],'s'),200);
ledger=lend(ledger,'h','s',300,date,'loan');
assert.equal(envelopeMovementEffect(ledger.movements[0],'h'),-300);
ledger=repay(ledger,ledger.loans[0].id,100,date,'repay');
assert.equal(envelopeMovementEffect(ledger.movements[0],'h'),100);assert.equal(envelopeMovementEffect(ledger.movements[0],'s'),-100);
const before=JSON.stringify(ledger),items=filterHistory(ledger.movements,{envelopeId:'h'}),sections=envelopeHistorySections(items);
assert.equal(sections[0].items.length,2);assert.equal(sections[1].items.length,1);assert.equal(sections[2].items.length,4);
assert.equal(new Set(sections.flatMap(section=>section.items.map(item=>item.id))).size,items.length);
assert.equal(items.reduce((sum,item)=>sum+envelopeMovementEffect(item,'h'),0),ledger.envelopes[0].balance);
assert.equal(envelopeMovementEffect({...items[0],type:'Transferencia',allocations:[{envelopeId:'h',name:'Hogar',amount:100},{name:'Antiguo',amount:100}]},'h'),null);
assert.equal(envelopeMovementEffect(items[0],'missing'),null);
assert.equal(JSON.stringify(ledger),before);
console.log('OK: importes parciales, siete operaciones, signos, agrupación sin duplicados, historia ambigua e inmutabilidad.');
