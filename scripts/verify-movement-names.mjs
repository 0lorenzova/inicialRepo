import assert from 'node:assert/strict';
import { normalizeNaming, buildMovementName, reorderNameFields, needsNameConfirmation } from '../lib/movement-names.ts';
import { postMovement, totals } from '../lib/finance-ledger.ts';

const legacy={fields:['Tipo de ingreso','Semana','Fecha','Monto','Monto','Número'],customNames:true};
const original=JSON.stringify(legacy), preferences=normalizeNaming(legacy);
assert.equal(JSON.stringify(legacy),original);
assert.deepEqual(preferences.Ingreso.fields,['Tipo de ingreso','Semana','Fecha','Monto','Número']);
assert.deepEqual(preferences.Gasto.fields,['Categoría','Fecha','Monto','Número']);
assert.equal(preferences.Gasto.manual,true);
const edited={...preferences,Ingreso:{manual:false,fields:['Monto','Fecha'],separator:' · '}};
const restored=normalizeNaming({naming:JSON.parse(JSON.stringify(edited))});
assert.deepEqual(restored,edited);assert.deepEqual(restored.Gasto,preferences.Gasto);
assert.deepEqual(normalizeNaming({naming:{Ingreso:{fields:['nonsense'],separator:'oops'}}}).Ingreso,{fields:[],separator:' - ',manual:false});
assert.deepEqual(reorderNameFields(['Fecha','Monto','Número'],'Número','Fecha'),['Número','Fecha','Monto']);
assert.deepEqual(reorderNameFields(['Fecha','Monto','Número'],'Fecha','Número'),['Monto','Número','Fecha']);
const context={kind:'Ingreso',date:'2026-01-01T02:30:00Z',amount:125000,incomeType:'Salario',category:'Alimentación',merchant:'Soda',sequence:53};
const settings={manual:false,fields:['Tipo de ingreso','Fecha','Hora','Semana','Monto','Número'],separator:' - '};
const name=buildMovementName(settings,context);
assert.match(name,/Salario - 31\/12\/2025 - 20:30 - Semana 1 - ₡125\s000 - #053/);
assert.equal(buildMovementName(settings,{...context,date:'2025-12-31T20:30'}),name);
assert.equal(buildMovementName({manual:false,fields:['Comercio','Categoría'],separator:' / '},{...context,kind:'Gasto'}),'Soda / Alimentación');
assert.equal(buildMovementName({manual:false,fields:[],separator:' '},{...context,amount:20}),'₡20');
assert.equal(buildMovementName({manual:false,fields:['Fecha','Hora','Semana'],separator:' '},{...context,date:'',amount:20}),'₡20');
assert.equal(needsNameConfirmation({...settings,manual:true},' ',name),true);
assert.equal(needsNameConfirmation({...settings,manual:true},name,name),true);
assert.equal(needsNameConfirmation({...settings,manual:true},'Pago especial',name),false);
assert.equal(needsNameConfirmation(settings,name,name),false);
const ledger={accounts:[{id:'cash',name:'Efectivo',type:'Efectivo',active:true,balance:0}],envelopes:[],loans:[],movements:[]};
const entered=postMovement(ledger,{id:'test-income-name',type:'Ingreso',amount:125000,date:'2026-10-07T10:24',accountId:'cash',envelopeAllocations:[],name,category:'Salario'});
assert.equal(entered.movements[0].name,name);
assert.deepEqual(totals(entered),{accounts:125000,assigned:0,unassigned:125000});
buildMovementName({...settings,separator:' / '},context);
assert.equal(entered.movements[0].name,name);assert.equal(ledger.movements.length,0);
console.log('OK: independent naming, legacy order, reordering, separators, Costa Rica/ISO dates, manual confirmation, persistence and immutable historical names.');
