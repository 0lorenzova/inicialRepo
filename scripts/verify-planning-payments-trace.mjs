import assert from "node:assert/strict";
import { postMovement, assign, unassign, totals } from "../lib/finance-ledger.ts";
import { incomeDistribution } from "../lib/income-trace.ts";
import { planningItems, proximityCounts, payScheduledAmount, saveScheduledAmount } from "../lib/envelope-planning.ts";
let ledger={accounts:[{id:"a",name:"Cuenta",type:"Banco",balance:0,active:true}],envelopes:[{id:"food",name:"Alimentación",balance:0},{id:"travel",name:"Viaje",balance:0}],loans:[],movements:[]};
const date="2026-10-03T09:00";
ledger=postMovement(ledger,{id:"income-a",type:"Ingreso",amount:100000,accountId:"a",envelopeAllocations:[{id:"food",amount:30000},{id:"travel",amount:40000}],date,name:"Salario"});
assert.equal(incomeDistribution(ledger,"income-a").unassigned,30000);
ledger=assign(ledger,"food",10000,date,"assignment-a");
assert.deepEqual(ledger.movements.find(m=>m.id==="assignment-a").incomeSources,[{incomeId:"income-a",amount:10000}]);
assert.equal(incomeDistribution(ledger,"income-a").assigned,80000);
assert.equal(incomeDistribution(ledger,"income-a").unassigned,20000);
assert.equal(ledger.movements.length,2,"No duplicate movements for provenance");
ledger=postMovement(ledger,{id:"unassigned-expense",type:"Gasto",amount:5000,accountId:"a",envelopeAllocations:[],date,name:"Gasto del fondo"});
assert.equal(incomeDistribution(ledger,"income-a").unassigned,15000);
assert.equal(incomeDistribution(ledger,"income-a").otherUses,5000);
ledger=postMovement(ledger,{id:"income-b",type:"Ingreso",amount:10000,accountId:"a",envelopeAllocations:[],date,name:"Extra"});
ledger=assign(ledger,"travel",20000,date,"assignment-b");
assert.deepEqual(ledger.movements.find(m=>m.id==="assignment-b").incomeSources,[{incomeId:"income-a",amount:15000},{incomeId:"income-b",amount:5000}]);
ledger=unassign(ledger,"food",5000,date,"unassign");
assert.equal(incomeDistribution(ledger,"income-a").unassigned,0,"Returned money does not invent a new income link");
const thresholds={green:60,yellow:20,red:5};
const base={name:"Importe",amount:9000,thresholds,active:true,timingEnabled:true};
const items=[{...base,id:"far",deadline:"2027-12-01"},{...base,id:"red",deadline:"2026-10-04"},{...base,id:"green",deadline:"2026-11-01"},{...base,id:"yellow",deadline:"2026-10-20"}];
ledger={...ledger,envelopes:ledger.envelopes.map(e=>e.id==="travel"?{...e,balanceHidden:true,scheduledAmounts:items}:e)};
const env=()=>ledger.envelopes.find(e=>e.id==="travel");
assert.deepEqual(planningItems(env(),date.slice(0,10)).map(i=>i.id),["red","yellow","green","far"]);
assert.deepEqual(proximityCounts(planningItems(env(),date.slice(0,10))),{green:1,yellow:1,red:1});
const before=structuredClone(ledger), startTotals=totals(ledger);
assert.throws(()=>payScheduledAmount(ledger,"travel","red",999999,"a",date),/suficiente/);
assert.throws(()=>payScheduledAmount(ledger,"travel","red",1,"missing",date),/cuenta/);
assert.deepEqual(ledger,before,"Failed payment is atomic");
ledger=payScheduledAmount(ledger,"travel","red",8000,"a",date);
assert.equal(totals(ledger).accounts,startTotals.accounts-8000);assert.equal(totals(ledger).assigned,startTotals.assigned-8000);assert.equal(totals(ledger).unassigned,startTotals.unassigned);
assert.equal(ledger.movements.length,before.movements.length+1);
assert.equal(ledger.movements[0].scheduledAmountId,"red");
assert.equal(env().scheduledAmounts.find(i=>i.id==="red").payment.amount,8000);
assert.equal(env().balanceHidden,true,"Privacy survives financial updates");
assert.deepEqual(proximityCounts(planningItems(env(),date.slice(0,10))),{green:1,yellow:1,red:0});
assert.throws(()=>payScheduledAmount(ledger,"travel","red",8000,"a",date),/ya está pagado/);
assert.throws(()=>saveScheduledAmount(ledger.envelopes,"travel",{...items[1],amount:1},items[1]),/pagado/);
for(const id of ["green","yellow"])ledger=payScheduledAmount(ledger,"travel",id,1000,"a",date);
assert.deepEqual(proximityCounts(planningItems(env(),date.slice(0,10))),{green:0,yellow:0,red:0},"White indicator after final near item paid; future item remains consultable");
assert.equal(planningItems(env(),date.slice(0,10)).length,4,"Paid history is retained");
assert.equal(JSON.stringify(JSON.parse(JSON.stringify(ledger))),JSON.stringify(ledger));
assert.equal(totals(ledger).accounts,totals(ledger).assigned+totals(ledger).unassigned);
const legacy={...before,movements:before.movements.map(m=>{const copy={...m};delete copy.incomeSources;return copy;})};
assert.equal(legacy.movements.find(m=>m.id==="assignment-a").incomeSources,undefined);
assert.ok(incomeDistribution(legacy,"income-a").otherUses>0);
console.log("OK: chronological counts, paid atomicity and duplicate protection, privacy persistence, partial income provenance, mixed origins and ledger equality.");
