import assert from 'node:assert/strict';
import { planningItems, planningCoverage, globalPlanningItems } from '../lib/envelope-planning.ts';
import { fundingOptions, incomeDistribution, postDistributedIncome } from '../lib/income-distribution.ts';
import { calendarEntries } from '../lib/planning-calendar.ts';
import { deriveFinanceNotifications } from '../lib/finance-notifications.ts';
const today='2026-10-10';
const item=(id,amount,deadline)=>({id,name:id,amount,deadline,active:true,timingEnabled:true});
const envelope={id:'a',name:'Hogar',balance:50000,scheduledAmounts:[item('third',15000,'2026-10-12'),item('first',20000,'2026-10-08'),item('second',25000,'2026-10-10')]};
const original=JSON.stringify(envelope);
const plans=planningItems(envelope,today);
assert.deepEqual(plans.map(p=>[p.id,p.covered,p.fundedAmount,p.shortfall]),[['first',true,20000,0],['second',true,25000,0],['third',false,5000,10000]]);
assert.equal(planningCoverage(plans),false);assert.equal(planningCoverage(plans.slice(0,2)),true);assert.equal(planningCoverage([]),undefined);
assert.equal(planningItems({...envelope,balance:-100},today).every(p=>p.fundedAmount===0&&!p.covered),true);
assert.equal(planningItems({...envelope,balance:60000},today).every(p=>p.covered),true);
const paid={...envelope,scheduledAmounts:envelope.scheduledAmounts.map(p=>p.id==='first'?{...p,payment:{amount:20000,movementId:'p',accountId:'bank',date:today}}:p)};
assert.equal(planningItems(paid,today).find(p=>p.id==='first').covered,undefined);
assert.equal(planningItems(paid,today).filter(p=>!p.payment).every(p=>p.covered),true);
const tied={...envelope,balance:1,scheduledAmounts:[item('b',1,today),item('a',1,today)]};
assert.deepEqual(planningItems(tied,today).map(p=>[p.id,p.covered]),[['a',true],['b',false]]);
assert.deepEqual(globalPlanningItems([{...envelope,archived:true}],today),[]);
assert.deepEqual(calendarEntries([envelope],today).map(e=>e.item.covered),[true,true,false]);
assert.deepEqual(fundingOptions([envelope],today).map(e=>e.item.covered),[true,true,false]);
assert.equal(deriveFinanceNotifications([],[envelope],today).find(e=>e.destination.itemId==='first').covered,true);
const ledger={accounts:[{id:'bank',name:'Cuenta',type:'Banco',balance:50000,active:true}],envelopes:[envelope],loans:[],movements:[]};
const option=fundingOptions([envelope],today).find(e=>e.item.id==='third');
const draft=incomeDistribution([envelope],today,15000,{},[option.selection]);
assert.equal(draft.total,15000);assert.equal(planningItems(envelope,today).at(-1).covered,false);
const funded=postDistributedIncome(ledger,{id:'income',accountId:'bank',amount:15000,date:today+'T12:00',name:'Prueba',paymentMethod:'SINPE Móvil'},today,{},[option.selection]);
assert.equal(planningItems(funded.envelopes[0],today).every(p=>p.covered),true);
assert.equal(funded.envelopes[0].scheduledAmounts.some(p=>p.payment),false);
assert.equal(funded.movements[0].paymentMethod,'SINPE Móvil');
assert.equal(JSON.stringify(envelope),original);
const five={...envelope,balance:500,scheduledAmounts:['2026-10-01','2026-10-10','2026-10-18','2026-10-25','2027-01-01'].map((date,i)=>item(String(i),100,date))};
assert.deepEqual(new Set(planningItems(five,today).map(p=>p.temporal?.tone??'white')),new Set(['purple','red','yellow','green','white']));
assert.equal(planningItems(five,today).every(p=>p.covered),true);
assert.equal(planningItems({...five,balance:0},today).every(p=>!p.covered),true);
assert.deepEqual(planningItems({...envelope,scheduledAmounts:[]},today),[]);
assert.equal(planningCoverage(planningItems({...five,balanceHidden:true},today)),undefined);
console.log('OK: cumulative coverage, partial funds, deficits, paid/archived items, stable tie order, shared calendar/distribution/notifications, draft isolation, confirmed funding without payment.');
