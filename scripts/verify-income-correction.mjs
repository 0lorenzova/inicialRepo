import assert from 'node:assert/strict';
import {postMovement,assign,unassign,totals} from '../lib/finance-ledger.ts';
import {correctionSnapshot,correctIncomeDistribution} from '../lib/income-correction.ts';
import {incomeDistribution,unassignedIncomeLots} from '../lib/income-trace.ts';
import {financialReport} from '../lib/finance-history.ts';
const day='2026-10-11T10:00';
let ledger={accounts:[{id:'a',name:'Cuenta',type:'Banco',active:true,balance:0}],envelopes:[{id:'h',name:'Hogar',balance:0},{id:'s',name:'Ahorro',balance:0}],movements:[],loans:[]};
ledger=postMovement(ledger,{id:'income',type:'Ingreso',name:'Ingreso original',amount:10000,accountId:'a',envelopeAllocations:[{id:'h',amount:4000},{id:'s',amount:2000}],date:'2026-10-10T10:00'});
const original=structuredClone(ledger),originalIncome=structuredClone(ledger.movements[0]);
const input=(state,amounts,id='batch')=>({incomeId:'income',expectedToken:correctionSnapshot(state,'income').token,amounts,reason:'Corrección ficticia',date:day,id});
ledger=correctIncomeDistribution(ledger,input(ledger,{h:2000,s:5000}));
assert.equal(ledger.envelopes[0].balance,2000);assert.equal(ledger.envelopes[1].balance,5000);
assert.deepEqual(ledger.accounts,original.accounts);assert.deepEqual(ledger.movements.find(m=>m.id==='income'),originalIncome);
assert.equal(ledger.movements.length,3);assert.equal(incomeDistribution(ledger,'income').assigned,7000);assert.equal(incomeDistribution(ledger,'income').unassigned,3000);
assert.equal(ledger.movements.filter(m=>m.distributionCorrection?.batchId==='batch').length,2);
assert.equal(financialReport(ledger.movements).income,10000);assert.equal(financialReport(ledger.movements).spent,0);
assert.equal(unassignedIncomeLots(ledger).reduce((sum,lot)=>sum+lot.amount,0),totals(ledger).unassigned);
const reject=(state,request,pattern)=>{const before=JSON.stringify(state);assert.throws(()=>correctIncomeDistribution(state,request),pattern);assert.equal(JSON.stringify(state),before);};
reject(ledger,input(ledger,{h:1000,s:5000}),/ya fue/);
reject(ledger,input(original,{h:3000,s:2000},'stale'),/cambió/);
reject(ledger,input(ledger,{h:2000,s:5000},'same'),/Modifica/);
for(const amounts of [{h:-1,s:100},{h:1.5,s:100},{h:10001},{missing:100},{h:Infinity}])reject(ledger,input(ledger,amounts,crypto.randomUUID()));
reject(ledger,{...input(ledger,{h:1000,s:5000},'date'),date:'2026-02-30T10:00'});
reject(ledger,{...input(ledger,{h:1000,s:5000},'past'),date:'2026-10-09T10:00'});
reject(ledger,{...input(ledger,{h:1000,s:5000},'reason'),reason:'  '});
ledger=correctIncomeDistribution(ledger,input(ledger,{h:1000,s:1000},'release'));
assert.equal(incomeDistribution(ledger,'income').unassigned,8000);
ledger=assign(ledger,'s',7500,day,'explicit','income');
assert.equal(incomeDistribution(ledger,'income').unassigned,500,'All lots of one income must be consumed without using other income lots');
assert.equal(incomeDistribution(ledger,'income').assigned,9500);
ledger=postMovement(ledger,{id:'expense',type:'Gasto',name:'Gasto',amount:1000,accountId:'a',envelopeAllocations:[{id:'s',amount:1000}],date:day});
reject(ledger,input(ledger,{h:9500,s:0},'spent'),/saldo suficiente/);
const archived={...ledger,envelopes:ledger.envelopes.map(e=>e.id==='s'?{...e,archived:true}:e)};
reject(archived,input(archived,{h:2000,s:7500},'archived'),/activo/);
const ambiguous={...original,movements:[{...originalIncome,allocations:[{name:'Antiguo',amount:4000}]}]};
assert.throws(()=>correctionSnapshot(ambiguous,'income'),/antiguos/);
const common=unassign(ledger,'h',100,day,'ordinary');
assert.ok(unassignedIncomeLots(common).some(lot=>!lot.incomeId&&lot.amount===100),'Normal withdrawals must remain unlinked');
const collision={...original,movements:[{...originalIncome,id:'collision:1',type:'Transferencia',amount:1,allocations:[]},...original.movements]};
reject(collision,input(collision,{h:2000,s:5000},'collision'),/ya existe/);
assert.equal(JSON.stringify(incomeDistribution(JSON.parse(JSON.stringify(ledger)),'income')),JSON.stringify(incomeDistribution(ledger,'income')));
assert.equal(totals(ledger).accounts,totals(ledger).assigned+totals(ledger).unassigned);
assert.deepEqual(original.movements[0],originalIncome);
const zoned={...original,movements:[{...originalIncome,date:'2026-10-11T15:00:00Z'}]};
const correctedZoned=correctIncomeDistribution(zoned,input(zoned,{h:3000,s:3000},'zone'));
assert.equal(incomeDistribution(correctedZoned,'income').unassigned,4000);
console.log('OK: corrección atómica, ingreso inmutable, trazabilidad, múltiples lotes, duplicados, concurrencia, fechas, fondos gastados, archivados, persistencia y conservación.');
