import assert from 'node:assert/strict';
import {postMovement,totals} from '../lib/finance-ledger.ts';
import {saveTrackedProduct,productReport} from '../lib/finance-products.ts';
const initial={accounts:[{id:'a',name:'Banco',type:'Banco',active:true,balance:0}],envelopes:[{id:'food',name:'Comida',balance:0},{id:'home',name:'Hogar',balance:0}],loans:[],movements:[]};
let ledger=postMovement(initial,{id:'income',type:'Ingreso',name:'Ficticio',amount:10000,accountId:'a',date:'2026-10-04T10:00',envelopeAllocations:[{id:'food',amount:6000},{id:'home',amount:4000}]});
ledger.envelopes=saveTrackedProduct(ledger.envelopes,'food',{id:'coffee',name:'Café',icon:'☕',tracking:true});
const expense={id:'expense',type:'Gasto',name:'Compra',amount:5000,accountId:'a',date:'2026-10-04T11:00',envelopeAllocations:[{id:'food',amount:3000},{id:'home',amount:2000}],products:[{name:'Café',amount:1500,quantity:2,notes:'Dos bolsas',envelopeId:'food',productId:'coffee'},{name:'Pan',amount:1000,envelopeId:'food'},{name:'Jabón',amount:1000,envelopeId:'home'}]};
const copy=structuredClone(ledger);
assert.throws(()=>postMovement(ledger,{...expense,products:[{name:'Café',amount:3001,envelopeId:'food'}]}),/sobre/);
assert.throws(()=>postMovement(ledger,{...expense,products:[{name:'Café',amount:100,envelopeId:'missing'}]}),/sobre/);
assert.throws(()=>postMovement(ledger,{...expense,products:[{name:'Café',amount:100,quantity:-1}]}),/cantidad/);
assert.throws(()=>postMovement(ledger,{...expense,products:[{name:'Café',amount:100,envelopeId:'home',productId:'coffee'}]}),/producto/);
assert.deepEqual(ledger,copy);
ledger=postMovement(ledger,expense);
assert.equal(totals(ledger).accounts,5000);
const food=productReport(ledger.movements,'food','2026-10'),home=productReport(ledger.movements,'home','2026-10');
assert.equal(food.spent,3000);assert.equal(food.identified,2500);assert.equal(food.withoutProduct,500);
assert.equal(home.spent,2000);assert.equal(home.identified,1000);assert.equal(home.withoutProduct,1000);
assert.equal(food.products.find(p=>p.id==='coffee').purchases[0].quantity,2);
assert.equal(food.products.find(p=>p.id==='coffee').percentage,50);
assert.equal(food.products.find(p=>p.id==='coffee').count,1);
ledger.envelopes=saveTrackedProduct(ledger.envelopes,'food',{id:'coffee',name:'Café nuevo',icon:'☕',tracking:false});
assert.equal(productReport(ledger.movements,'food','2026-10').identified,2500);
assert.equal(ledger.envelopes[0].balance,3000);
assert.equal(productReport(ledger.movements,'food','2026-11').spent,0);
assert.equal(totals(ledger).accounts,totals(ledger).assigned+totals(ledger).unassigned);
console.log('OK: varios productos, limites por gasto/sobre, cantidades, seguimiento, historial, reporte mensual sin doble conteo y atomico.');
