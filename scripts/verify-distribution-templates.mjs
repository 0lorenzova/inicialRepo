import assert from 'node:assert/strict';
import {createDistributionTemplate,templateAllocations} from '../lib/distribution-templates.ts';
import {incomeDistribution,postDistributedIncome} from '../lib/income-distribution.ts';
import {totals} from '../lib/finance-ledger.ts';
const envelopes=[{id:'a',name:'Hogar',balance:0},{id:'b',name:'Ahorro',balance:0}];
const allocations=[{id:'a',amount:100},{id:'b',amount:200}];
const templates=createDistributionTemplate([],' Semana ',allocations,envelopes,'template');
allocations[0].amount=999;
assert.equal(templates[0].allocations[0].amount,100);
assert.equal(templates[0].name,'Semana');
const manual=templateAllocations(templates[0],envelopes,500);
assert.deepEqual(manual,{a:'100',b:'200'});
assert.equal(incomeDistribution(envelopes,'2026-10-10',500,manual,[]).remaining,200);
assert.throws(()=>templateAllocations(templates[0],envelopes,250));
assert.throws(()=>templateAllocations(templates[0],[envelopes[0],{...envelopes[1],archived:true}],500));
assert.throws(()=>createDistributionTemplate(templates,'semana',[],envelopes,'other'));
assert.throws(()=>createDistributionTemplate([],'Vacía',[],envelopes,'empty'));
assert.throws(()=>templateAllocations({...templates[0],allocations:[{id:'a',amount:1},{id:'a',amount:2}]},envelopes,500));
const ledger={accounts:[{id:'bank',name:'Cuenta',type:'Banco',active:true,balance:0}],envelopes,loans:[],movements:[]};
const next=postDistributedIncome(ledger,{id:'new',accountId:'bank',amount:500,name:'Ingreso',date:'2026-10-10T12:00'},'2026-10-10',manual,[]);
assert.equal(next.movements.length,1);assert.equal(ledger.movements.length,0);
assert.equal(totals(next).accounts,500);assert.equal(totals(next).assigned,300);assert.equal(totals(next).unassigned,200);
assert.deepEqual(JSON.parse(JSON.stringify(templates)),templates);
console.log('OK: templates preserve amounts and identity, reject duplicates/archived/excess, apply only to a draft and use atomic income confirmation.');
