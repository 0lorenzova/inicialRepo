import assert from "node:assert/strict";
import { plannedPaymentDelay, planningItems, saveScheduledAmount, payScheduledAmount, moveScheduledAmount, validateScheduledAmount } from "../lib/envelope-planning.ts";
import { saveGoalSettings } from "../lib/envelope-settings.ts";
import { moveEnvelopeGoal } from "../lib/move-envelope-goal.ts";
import { calendarEntries, calendarRange } from "../lib/planning-calendar.ts";
import { isoWeek } from "../lib/iso-week.ts";
import { saveTrackedProduct } from "../lib/finance-products.ts";
import { postMovement, totals } from "../lib/finance-ledger.ts";

const today="2026-10-13";
const responsibility={id:"electricity",name:"Electricidad",amount:100,deadline:"2026-10-25",plannedPaymentDate:"2026-10-28",active:true,timingEnabled:true,repetition:{frequency:"monthly",anchorDay:25,seriesId:"electricity"}};
let ledger=postMovement({accounts:[{id:"a",name:"Prueba",type:"Banco",active:true,balance:0}],envelopes:[{id:"home",name:"Hogar",icon:"🏠",balance:0},{id:"other",name:"Otro",icon:"📦",balance:0}],loans:[],movements:[]},{id:"income",type:"Ingreso",name:"Ficticio",date:`${today}T10:00`,amount:1000,accountId:"a",envelopeAllocations:[{id:"home",amount:800}]});
const financialBefore=JSON.stringify({accounts:ledger.accounts,movements:ledger.movements,totals:totals(ledger)});
ledger.envelopes=saveScheduledAmount(ledger.envelopes,"home",responsibility,null);
const items=()=>planningItems(ledger.envelopes[0],today);
assert.equal(plannedPaymentDelay(items()[0]),3);
assert.equal(items()[0].temporal.tone,"green","Proximity uses deadline, not planned payment");
assert.equal(items()[0].covered,true,"Full coverage does not stop the warning");
assert.equal(calendarEntries(ledger.envelopes,today)[0].date,responsibility.deadline);
assert.equal(JSON.parse(JSON.stringify(ledger)).envelopes[0].scheduledAmounts[0].plannedPaymentDate,"2026-10-28");
for(const plannedPaymentDate of [undefined,"2026-10-24","2026-10-25"]) assert.equal(plannedPaymentDelay({...items()[0],plannedPaymentDate}),0);
assert.equal(plannedPaymentDelay({...items()[0],payment:{movementId:"paid"}}),0);
assert.equal(plannedPaymentDelay({...items()[0],plannedPaymentDate:"invalid"}),0);
assert.throws(()=>validateScheduledAmount({...responsibility,plannedPaymentDate:"2026-02-30"}),/prevista/);
assert.equal(planningItems({...ledger.envelopes[0],scheduledAmounts:[{...responsibility,active:false}]},today).length,0);
assert.throws(()=>saveScheduledAmount(ledger.envelopes,"home",{...responsibility,name:"Changed"},{...responsibility,plannedPaymentDate:"2026-10-29"}),/cambió/);
const moved=moveScheduledAmount(ledger.envelopes,"home","other",responsibility);
assert.equal(planningItems(moved[0],today).some(item=>plannedPaymentDelay(item)>0),false);
assert.equal(plannedPaymentDelay(planningItems(moved[1],today)[0]),3);
assert.equal(moved[0].balance,800);

for(const [id,tracking] of [["coffee",true],["bread",true],["coffee",false]]) ledger.envelopes=saveTrackedProduct(ledger.envelopes,"home",{id,name:id,icon:"📦",tracking});
assert.deepEqual(ledger.envelopes[0].products.map(p=>p.tracking),[false,true],"Independent multiple selection");
assert.equal(JSON.stringify({accounts:ledger.accounts,movements:ledger.movements,totals:totals(ledger)}),financialBefore,"Planning and tracking never change money");
ledger=payScheduledAmount(ledger,"home","electricity",100,"a",`${today}T10:00`);
assert.equal(items().some(item=>plannedPaymentDelay(item)>0),false,"Payment closes this occurrence's warning");
assert.equal(ledger.envelopes[0].scheduledAmounts[0].plannedPaymentDate,"2026-10-28","Paid history retains the plan");
assert.equal(ledger.envelopes[0].scheduledAmounts[1].deadline,"2026-11-25");
assert.equal(ledger.envelopes[0].scheduledAmounts[1].plannedPaymentDate,undefined,"Next occurrence must not inherit an absolute past date");
ledger.envelopes=saveScheduledAmount(ledger.envelopes,"home",{...responsibility,id:"second",repetition:undefined},null);
assert.equal(items().some(item=>plannedPaymentDelay(item)>0),true,"Other unpaid late plans keep warning active");
assert.equal(totals(ledger).accounts,totals(ledger).assigned+totals(ledger).unassigned);
const original=ledger.envelopes[0];
const goal=saveGoalSettings(ledger.envelopes,{...original,goal:100,goalEnabled:true,goalDate:"2026-10-25",goalPlannedPaymentDate:"2026-10-30"},original);
assert.equal(plannedPaymentDelay(planningItems(goal[0],today).find(p=>p.kind==="goal")),5);
const movedGoal=moveEnvelopeGoal(goal,goal[0],"other","goal-test");
assert.equal(movedGoal[0].goalPlannedPaymentDate,undefined);
assert.equal(movedGoal[1].goalPlannedPaymentDate,"2026-10-30");
assert.equal(planningItems({...goal[0],goalEnabled:false},today).some(p=>p.kind==="goal"),false);
assert.deepEqual(calendarRange(today,"Semana"),{from:"2026-10-12",to:"2026-10-18"});
assert.equal(isoWeek(today).week,42);
assert.equal(isoWeek("2027-01-01").week,53);
console.log("OK: planned date persistence, delay, independent proximity/coverage, correction/cancellation/payment, recurrence, moves, conflicts, multiple product selection and unchanged financial invariants.");

