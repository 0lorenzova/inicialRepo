import assert from 'node:assert/strict';
import {filterHistory, financialReport, movementDay, monthRange, historyRangeError} from '../lib/finance-history.ts';
const base={allocations:[],amount:100,name:'Prueba',type:'Ingreso'};
const items=[{...base,id:'sep',date:'2026-10-01T05:59:00Z'},{...base,id:'oct',date:'2026-10-01T06:00:00Z',amount:1000},{...base,id:'expense',date:'2026-10-02T10:30',type:'Gasto',amount:500,category:'Alimentación',merchant:'Café',reference:'Factura 123',description:'Almuerzo',allocations:[{envelopeId:'new',name:'Viaje',amount:300}]},{...base,id:'loan',date:'2026-10-02T10:30',type:'Préstamo',amount:900}];
assert.equal(movementDay(items[0].date),'2026-09-30');
assert.equal(movementDay(items[1].date),'2026-10-01');
assert.deepEqual(filterHistory(items,{from:'2026-10-01',to:'2026-10-01'}).map(m=>m.id),['oct']);
assert.deepEqual(filterHistory(items,{envelopeId:'new',search:'cafe',type:'Gasto'}).map(m=>m.id),['expense']);
assert.equal(filterHistory(items,{search:'Factura 123'}).length,1);
assert.equal(filterHistory(items,{search:'almuerzo'}).length,1);
assert.equal(filterHistory(items,{from:'2026-11-01',to:'2026-10-01'}).length,0);
assert.ok(historyRangeError('2026-02-30',''));
assert.deepEqual(monthRange('2028-02'),{from:'2028-02-01',to:'2028-02-29'});
const before=JSON.stringify(items), report=financialReport(items,'2026-10');
assert.equal(report.income,1000);assert.equal(report.spent,500);assert.equal(report.net,500);assert.equal(report.withoutEnvelope,200);
assert.deepEqual(report.envelopes,[{id:'new',name:'Viaje',spent:300}]);
assert.equal(financialReport(items).income,1100);
assert.equal(financialReport(items,'2026-12').count,0);
assert.equal(JSON.stringify(items),before);
console.log('OK: fechas Costa Rica, limites inclusivos, rango invalido, busqueda sin acentos y por referencia, sobres nuevos, meses y reportes sin duplicar prestamos.');
